// Regenerates migrations/0001_seed_taxonomy.sql from scripts/taxonomy.mjs.
// Only for a fresh project: once a migration has been applied anywhere, add a new migration instead.
import { writeFileSync } from "node:fs";
import { categories, suburbs } from "./taxonomy.mjs";

const q = (v) => (typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- Launch taxonomy for Pune. Generated by scripts/gen-taxonomy-sql.mjs from scripts/taxonomy.mjs."];

suburbs.forEach((s, i) => {
	lines.push(`INSERT INTO suburb (id, name, city, sort_order, active) VALUES (${q(s.id)}, ${q(s.name)}, 'Pune', ${i}, 1);`);
});
categories.forEach((c, ci) => {
	lines.push(`INSERT INTO category (id, name, emoji, blurb, sort_order, active) VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.emoji)}, ${q(c.blurb)}, ${ci}, 1);`);
	c.subcategories.forEach((s, si) => {
		lines.push(`INSERT INTO subcategory (id, category_id, name, emoji, blurb, sort_order, active) VALUES (${q(s.id)}, ${q(c.id)}, ${q(s.name)}, ${q(s.emoji)}, ${q(s.blurb)}, ${si}, 1);`);
		s.prompts.forEach((p, pi) => {
			lines.push(
				`INSERT INTO prompt (id, subcategory_id, question, kind, options, max_select, template, sort_order, active) VALUES (${q(`${s.id}-q${pi + 1}`)}, ${q(s.id)}, ${q(p.question)}, ${q(p.kind)}, ${q(JSON.stringify(p.options))}, ${p.maxSelect}, ${q(p.template)}, ${pi}, 1);`,
			);
		});
	});
});

writeFileSync(new URL("../migrations/0001_seed_taxonomy.sql", import.meta.url), lines.join("\n--> statement-breakpoint\n") + "\n");
console.log(`Wrote ${lines.length - 1} statements`);
